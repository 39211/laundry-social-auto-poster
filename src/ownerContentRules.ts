interface Hit {
  start: number;
  end: number;
  groups: Array<string | undefined>;
}

interface TextField {
  field: string;
  text: string;
}

function nfkc(value: string): string {
  return value.normalize("NFKC");
}

function findAll(text: string, re: RegExp): Hit[] {
  const flags = re.flags.includes("g") ? re.flags : `${re.flags}g`;
  const global = new RegExp(re.source, flags);
  const hits: Hit[] = [];
  let match: RegExpExecArray | null;
  while ((match = global.exec(text)) !== null) {
    if (match[0].length === 0) {
      global.lastIndex += 1;
      continue;
    }
    hits.push({ start: match.index, end: match.index + match[0].length, groups: Array.from(match) });
  }
  return hits;
}

function isLowSurrogate(code: number): boolean {
  return code >= 0xdc00 && code <= 0xdfff;
}

function excerptAround(text: string, start: number, end: number): string {
  let s: number;
  let e: number;
  if (end - start >= EXCERPT_MAX) {
    s = start;
    e = start + EXCERPT_MAX;
  } else {
    const pad = Math.floor((EXCERPT_MAX - (end - start)) / 2);
    s = Math.max(0, start - pad);
    e = Math.min(text.length, s + EXCERPT_MAX);
    s = Math.max(0, e - EXCERPT_MAX);
  }
  if (s > 0 && isLowSurrogate(text.charCodeAt(s))) s += 1;
  if (e < text.length && isLowSurrogate(text.charCodeAt(e))) e -= 1;
  return text.slice(s, e).replace(/\s+/g, " ").trim();
}

function boundsAround(text: string, start: number, end: number, delimiter: RegExp): [number, number] {
  let s = start;
  while (s > 0 && !delimiter.test(text.charAt(s - 1))) s -= 1;
  let e = end;
  while (e < text.length && !delimiter.test(text.charAt(e))) e += 1;
  return [s, e];
}

function segments(text: string, delimiter: RegExp): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (delimiter.test(text.charAt(i))) {
      if (i > start) out.push([start, i]);
      start = i + 1;
    }
  }
  if (start < text.length) out.push([start, text.length]);
  return out;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function stringList(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : [];
}

function pushText(out: TextField[], field: string, value: unknown): void {
  if (typeof value === "string") {
    if (value.trim().length > 0) out.push({ field, text: nfkc(value) });
    return;
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => {
      if (typeof item === "string" && item.trim().length > 0) {
        out.push({ field: `${field}[${index}]`, text: nfkc(item) });
      }
    });
  }
}

function carouselItems(record: Record<string, unknown>): Array<Record<string, unknown>> {
  const items = record.carousel_items;
  return Array.isArray(items) ? items.filter(isObject) : [];
}

function publishedTextFields(record: Record<string, unknown>): TextField[] {
  const out: TextField[] = [];
  pushText(out, "facebook_caption", record.facebook_caption);
  pushText(out, "instagram_caption", record.instagram_caption);
  for (const key of Object.keys(record)) {
    if (key.includes("first_comment")) pushText(out, key, record[key]);
  }
  carouselItems(record).forEach((item, index) => {
    for (const key of Object.keys(item)) {
      if (key === "caption" || key === "text" || key.endsWith("_caption") || key.endsWith("_text")) {
        pushText(out, `carousel_items[${index}].${key}`, item[key]);
      }
    }
  });
  return out;
}

function promptFields(record: Record<string, unknown>): TextField[] {
  const out: TextField[] = [];
  for (const key of Object.keys(record)) {
    if (key.endsWith("_prompt")) pushText(out, key, record[key]);
  }
  const candidate = record.video_candidate;
  if (isObject(candidate)) {
    for (const key of Object.keys(candidate)) {
      if (key.endsWith("_prompt")) pushText(out, `video_candidate.${key}`, candidate[key]);
    }
  }
  carouselItems(record).forEach((item, index) => {
    for (const key of Object.keys(item)) {
      if (key === "prompt" || key.endsWith("_prompt")) {
        pushText(out, `carousel_items[${index}].${key}`, item[key]);
      }
    }
  });
  return out;
}

/** Parses a day/week count; returns [low, high] (a colloquial 三四 is [3, 4]) or null. */
function parseCount(raw: string): [number, number] | null {
  if (/^\d+(?:\.\d+)?$/.test(raw)) {
    const n = Number(raw);
    return Number.isFinite(n) ? [n, n] : null;
  }
  const tens = /^([一二兩三四五六七八九])?([十廿])([一二三四五六七八九])?$/.exec(raw);
  if (tens) {
    const lead = tens[1];
    const unit = tens[2];
    const tail = tens[3];
    let tensValue: number;
    if (unit === "廿") {
      if (lead) return null;
      tensValue = 2;
    } else {
      tensValue = lead ? CN_DIGIT[lead] ?? Number.NaN : 1;
    }
    const value = tensValue * 10 + (tail ? CN_DIGIT[tail] ?? Number.NaN : 0);
    return Number.isFinite(value) ? [value, value] : null;
  }
  const chars = Array.from(raw);
  const first = chars[0];
  if (chars.length === 1 && first !== undefined) {
    const d = CN_DIGIT[first];
    return d === undefined ? null : [d, d];
  }
  const second = chars[1];
  if (chars.length === 2 && first !== undefined && second !== undefined) {
    const a = CN_DIGIT[first];
    const b = CN_DIGIT[second];
    if (a !== undefined && b !== undefined && b === a + 1) return [a, b];
  }
  return null;
}

const CN_UNIT: Record<string, number> = { 十: 10, 百: 100, 千: 1000 };

/**
 * Parses a Chinese-numeral amount: 七十=70, 三百五十=350, 三百五=350, 一千二=1200,
 * 一千二百=1200, 兩千=2000, 一千零五=1005, 十五=15, 兩萬五=25000.
 * Returns null for anything that cannot be read unambiguously (三四 / 三四百 ranges,
 * digit-by-digit 一〇〇, units out of order such as 百千), so the caller keeps blocking.
 */
export function parseChineseAmount(raw: string): number | null {
  const chars = Array.from(raw);
  if (chars.length === 0) return null;
  let total = 0; // the 萬 part
  let section = 0; // below 萬
  let sectionUnit = Number.POSITIVE_INFINITY;
  let lastUnit = 0;
  let pending: number | null = null;
  let zero = false;
  let wan = false;
  for (const ch of chars) {
    if (ch === "零" || ch === "〇") {
      if (pending !== null) return null;
      zero = true;
      continue;
    }
    const digit = CN_DIGIT[ch];
    if (digit !== undefined) {
      if (pending !== null) return null;
      pending = digit;
      continue;
    }
    const unit = CN_UNIT[ch];
    if (unit !== undefined) {
      if (unit >= sectionUnit) return null;
      let multiplier: number;
      if (pending !== null) multiplier = pending;
      else if (lastUnit === 0 && !zero) multiplier = 1; // leading 十/百/千 means one
      else return null;
      section += multiplier * unit;
      sectionUnit = unit;
      lastUnit = unit;
      pending = null;
      zero = false;
      continue;
    }
    if (ch === "萬") {
      if (wan) return null;
      // 一千二萬 could be 1,200 萬 or 1,002 萬: refuse rather than guess.
      if (pending !== null && !zero && sectionUnit !== Number.POSITIVE_INFINITY && sectionUnit !== 10) return null;
      let value = section + (pending ?? 0);
      if (value === 0) {
        if (lastUnit !== 0 || zero) return null;
        value = 1;
      }
      total = value * 10000;
      section = 0;
      sectionUnit = Number.POSITIVE_INFINITY;
      lastUnit = 10000;
      pending = null;
      zero = false;
      wan = true;
      continue;
    }
    return null;
  }
  if (pending !== null) {
    // 一千零五 adds 5; 一千二 / 三百五 / 兩萬五 abbreviate the next lower unit.
    section += zero || lastUnit === 0 ? pending : pending * (lastUnit / 10);
  }
  return total + section;
}

/** Amounts in one price hit. Empty when any amount cannot be read (the hit then blocks). */
function priceHitAmounts(hitText: string, precededByDigit: boolean): number[] {
  const digitAmounts = (hitText.match(/\d+/g) ?? []).map(Number);
  if (digitAmounts.length > 0) return digitAmounts;
  // 「5千元」: the Chinese pattern only sees 千元, which would read as 1000.
  if (precededByDigit) return [];
  const runs = hitText.match(/[零〇一二兩三四五六七八九十百千萬]+/g) ?? [];
  const amounts: number[] = [];
  for (const run of runs) {
    const value = parseChineseAmount(run);
    if (value === null) return [];
    amounts.push(value);
  }
  return amounts;
}

/**
 * Duration the pipeline stored for the slot's video when the video source was
 * marked (VideoSourceRecord.duration_seconds, probe results). Matches the same
 * record validatePublishableReel accepts: same slot, grok-imagine-video source,
 * same video_path. Unknown (undefined) when there is no such record, when a
 * matching record carries no valid duration, or when matching records disagree.
 * Pure: the caller loads the records (autoApprove uses loadVideoSources).
 */
export function storedReelDurationSeconds(slot: object, sources: readonly object[]): number | undefined {
  const record = slot as Record<string, unknown>;
  const path = record.local_video_path;
  if (typeof path !== "string" || path.length === 0) return undefined;
  const durations = new Set<number>();
  for (const entry of sources) {
    if (!isObject(entry)) continue;
    if (entry.slot !== record.slot || entry.source !== "grok-imagine-video" || entry.video_path !== path) continue;
    const seconds = entry.duration_seconds;
    if (typeof seconds !== "number" || !Number.isFinite(seconds) || seconds <= 0) return undefined;
    durations.add(seconds);
  }
  return durations.size === 1 ? [...durations][0] : undefined;
}

function plannedVideoSeconds(record: Record<string, unknown>): number | undefined {
  const candidate = record.video_candidate;
  if (isObject(candidate) && typeof candidate.duration_seconds === "number") return candidate.duration_seconds;
  return undefined;
}

function formatSeconds(value: number): string {
  return Number.isInteger(value) ? String(value) : value.toFixed(1);
}

/**
 * Checks one calendar slot against the owner's rules. Accepts any object so a
 * DailySlot, a raw calendar JSON slot or a test fixture can be passed as-is.
 */
export function checkSlotAgainstOwnerRules(slot: object, opts: OwnerRulesOptions = {}): OwnerRuleViolation[] {
  const record = slot as Record<string, unknown>;
  const rules = OWNER_CONTENT_RULES;
  const out: OwnerRuleViolation[] = [];
  const taken = new Map<string, Array<[number, number]>>();

  const add = (
    rule: OwnerRuleId,
    severity: OwnerRuleSeverity,
    field: string,
    text: string,
    start: number,
    end: number
  ): void => {
    const key = `${rule}\u0000${field}`;
    const spans = taken.get(key) ?? [];
    if (spans.some(([s, e]) => start < e && end > s)) return;
    spans.push([start, end]);
    taken.set(key, spans);
    out.push({ rule, severity, field, excerpt: excerptAround(text, start, end) });
  };

  const allowedPrices = [...stringList(record.owner_supplied_prices), ...(opts.ownerSuppliedPrices ?? [])]
    .map(nfkc)
    .filter((price) => price.trim().length > 0);

  for (const { field, text } of publishedTextFields(record)) {
    const urlSpans = findAll(text, URL_RE).map((hit): [number, number] => [hit.start, hit.end]);
    const inUrl = (start: number, end: number) => urlSpans.some(([s, e]) => start >= s && end <= e);

    // 1. AI label
    for (const pattern of rules.ai_label.patterns) {
      for (const hit of findAll(text, pattern.re)) add("ai_label", "block", field, text, hit.start, hit.end);
    }

    // 2. Fabrication
    for (const pattern of rules.fabrication.patterns) {
      for (const hit of findAll(text, pattern.re)) {
        if (inUrl(hit.start, hit.end)) continue;
        add("fabrication", "block", field, text, hit.start, hit.end);
      }
    }

    // 3. Turnaround
    const turnaround = rules.turnaround;
    const counters: Array<[RegExp, number]> = [
      [turnaround.day_count, 1],
      [turnaround.week_count, 7]
    ];
    for (const [re, multiplier] of counters) {
      for (const hit of findAll(text, re)) {
        if (inUrl(hit.start, hit.end)) continue;
        const [cs, ce] = boundsAround(text, hit.start, hit.end, turnaround.clause_delimiter);
        if (!turnaround.context.test(text.slice(cs, ce))) continue;
        const firstRaw = hit.groups[1];
        const secondRaw = hit.groups[2];
        const first = firstRaw === undefined ? null : parseCount(firstRaw);
        const second = secondRaw === undefined ? undefined : parseCount(secondRaw);
        let allowed = false;
        if (first && second !== null) {
          const low = first[0] * multiplier;
          const high = (second ?? first)[1] * multiplier;
          const same = ([a, b]: readonly [number, number]) => a === low && b === high;
          const clause = text.slice(cs, ce);
          const items = turnaround.item_spans.filter((item) => item.re.test(clause));
          allowed =
            items.length === 0
              ? turnaround.allowed_spans.some(same)
              : items.every((item) => item.spans.some(same));
        }
        if (!allowed) add("turnaround", "block", field, text, hit.start, hit.end);
      }
    }
    for (const hit of findAll(text, turnaround.express)) {
      if (inUrl(hit.start, hit.end)) continue;
      add("turnaround", "block", field, text, hit.start, hit.end);
    }

    // 4. Price
    const allowedSpans: Array<[number, number]> = [];
    for (const price of allowedPrices) {
      let index = text.indexOf(price);
      while (index !== -1) {
        allowedSpans.push([index, index + price.length]);
        index = text.indexOf(price, index + 1);
      }
    }
    for (const pattern of rules.price.patterns) {
      for (const hit of findAll(text, pattern.re)) {
        if (inUrl(hit.start, hit.end)) continue;
        if (allowedSpans.some(([s, e]) => hit.start >= s && hit.end <= e)) continue;
        const precededByDigit = hit.start > 0 && /\d/.test(text.charAt(hit.start - 1));
        const amounts = priceHitAmounts(text.slice(hit.start, hit.end), precededByDigit);
        const onList = amounts.length > 0 && amounts.every((amount) => (opts.priceListAmounts ?? []).includes(amount));
        add("price", onList ? "warn" : "block", field, text, hit.start, hit.end);
      }
    }

    // 5. Placeholder
    for (const pattern of rules.placeholder.patterns) {
      for (const hit of findAll(text, pattern.re)) add("placeholder", "block", field, text, hit.start, hit.end);
    }
  }

  // 6. Slim master (prompts only)
  const slim = rules.slim_master;
  for (const { field, text } of promptFields(record)) {
    for (const [s, e] of segments(text, slim.sentence_delimiter)) {
      const sentence = text.slice(s, e);
      if (!slim.person.test(sentence)) continue;
      for (const pattern of slim.slimming) {
        for (const hit of findAll(sentence, pattern.re)) {
          if (slim.negation.test(sentence.slice(0, hit.start))) continue;
          add("slim_master", "block", field, text, s + hit.start, s + hit.end);
        }
      }
    }
  }

  // 7. Reel length
  if (record.media_type === "reel") {
    const reel = rules.reel_length;
    const duration = opts.reelDurationSeconds;
    if (typeof duration === "number" && Number.isFinite(duration)) {
      if (duration < reel.min_seconds || duration > reel.max_seconds) {
        out.push({
          rule: "reel_length",
          severity: "block",
          field: "video",
          excerpt: `影片 ${formatSeconds(duration)} 秒，須 ${reel.min_seconds}–${reel.max_seconds} 秒`.slice(0, EXCERPT_MAX)
        });
      }
    } else {
      const planned = plannedVideoSeconds(record);
      const note =
        planned === undefined
          ? `時長未知，須 ${reel.min_seconds}–${reel.max_seconds} 秒`
          : `時長未知（規劃 ${formatSeconds(planned)} 秒），須 ${reel.min_seconds}–${reel.max_seconds} 秒`;
      out.push({ rule: "reel_length", severity: "warn", field: "video", excerpt: note.slice(0, EXCERPT_MAX) });
    }
  }

  return out;
}

export type OwnerRulesMode = "report" | "block" | "off";

/** SXJ_OWNER_RULES: report (default) | block | off. Unknown values run as report. */
export function parseOwnerRulesMode(raw: string | undefined): { mode: OwnerRulesMode; unrecognized?: string } {
  const value = (raw ?? "").trim().toLowerCase();
  if (value === "") return { mode: "report" };
  if (value === "report" || value === "block" || value === "off") return { mode: value };
  return { mode: "report", unrecognized: raw };
}

export function formatOwnerRuleViolations(violations: readonly OwnerRuleViolation[], limit = 8): string {
  const shown = violations
    .slice(0, limit)
    .map((v) => `${v.rule}(${v.severity}) ${v.field}「${v.excerpt}」`);
  if (violations.length > limit) shown.push(`+${violations.length - limit} more`);
  return shown.join("; ");
}
