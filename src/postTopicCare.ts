export function resolvePostTopicCare(input: string | { topic: string; title?: string }): PostTopicCare | undefined {
  const topic = (typeof input === 'string' ? input : input.topic || input.title || '').normalize('NFKC').trim();
  if (!topic) return undefined;
  const found = RULES.find(({ match }) => match.test(topic));
  if (!found) return undefined;
  // Callers may add page-specific checks without changing subsequent resolutions.
  return { ...found.care, keywords: [...found.care.keywords], paragraphs: [...found.care.paragraphs], guideSlugs: [...found.care.guideSlugs], checkpoints: [...found.care.checkpoints],
    faqs: found.care.faqs.map(faq => ({ ...faq })) };
}
